package slo

import (
	"fmt"
	"strings"

	"gopkg.in/yaml.v3"
)

// Windows used by the multiwindow, multi-burn-rate alerts (Google SRE workbook, ch. 5).
var Windows = []string{"5m", "30m", "1h", "6h", "1d", "3d"}

type rule struct {
	Record      string            `yaml:"record,omitempty"`
	Alert       string            `yaml:"alert,omitempty"`
	Expr        string            `yaml:"expr"`
	For         string            `yaml:"for,omitempty"`
	Labels      map[string]string `yaml:"labels,omitempty"`
	Annotations map[string]string `yaml:"annotations,omitempty"`
}

type group struct {
	Name     string `yaml:"name"`
	Interval string `yaml:"interval,omitempty"`
	Rules    []rule `yaml:"rules"`
}

// RatioRecord is the recording-rule name for the error ratio over a window.
func RatioRecord(window string) string { return "slo:error_ratio:rate" + window }

func (s *Spec) selector() string {
	return fmt.Sprintf(`{service=%q, slo=%q}`, s.Service, s.Name)
}

func (s *Spec) labels() map[string]string {
	return map[string]string{"service": s.Service, "slo": s.Name}
}

func (s *Spec) ratioExpr(window string) string {
	return fmt.Sprintf("sum(rate(%s[%s])) / clamp_min(sum(rate(%s[%s])), 1e-9)",
		strings.TrimSpace(s.SLI.Errors), window, strings.TrimSpace(s.SLI.Total), window)
}

// Groups returns the recording and alerting rules for one SLO.
func (s *Spec) Groups() []group {
	rec := group{Name: fmt.Sprintf("slo-%s-%s-recording", s.Service, s.Name), Interval: "30s"}
	for _, w := range append(append([]string{}, Windows...), s.Window) {
		rec.Rules = append(rec.Rules, rule{Record: RatioRecord(w), Expr: s.ratioExpr(w), Labels: s.labels()})
	}
	rec.Rules = append(rec.Rules,
		rule{Record: "slo:objective", Expr: fmt.Sprintf("vector(%g)", s.Objective), Labels: s.labels()},
		rule{
			Record: "slo:error_budget_remaining",
			Expr:   fmt.Sprintf("1 - (%s%s / %g)", RatioRecord(s.Window), s.selector(), s.ErrorBudget()),
			Labels: s.labels(),
		},
	)

	burn := func(w string) string { return fmt.Sprintf("%s%s / %g", RatioRecord(w), s.selector(), s.ErrorBudget()) }
	ann := func(summary, runbook string) map[string]string {
		return map[string]string{"summary": summary, "runbook_url": runbook,
			"description": fmt.Sprintf("SLO %s/%s (%.4g%% over %s), owner %s", s.Service, s.Name, s.Objective*100, s.Window, s.Owner)}
	}
	alerts := group{Name: fmt.Sprintf("slo-%s-%s-alerts", s.Service, s.Name)}
	alerts.Rules = []rule{
		{
			Alert:       "SLOFastBurn",
			Expr:        fmt.Sprintf("(%s > 14.4) and (%s > 14.4)", burn("1h"), burn("5m")),
			For:         "2m",
			Labels:      map[string]string{"severity": "page", "service": s.Service, "slo": s.Name},
			Annotations: ann(fmt.Sprintf("%s burning its error budget 14x: 2%% of the budget per hour", s.Service), "08-sre-operations/runbooks/slo-burn.md"),
		},
		{
			Alert:       "SLOSlowBurn",
			Expr:        fmt.Sprintf("(%s > 6) and (%s > 6)", burn("6h"), burn("30m")),
			For:         "15m",
			Labels:      map[string]string{"severity": "page", "service": s.Service, "slo": s.Name},
			Annotations: ann(fmt.Sprintf("%s burning its error budget 6x over 6h", s.Service), "08-sre-operations/runbooks/slo-burn.md"),
		},
		{
			Alert:       "SLOBudgetLeak",
			Expr:        fmt.Sprintf("(%s > 1) and (%s > 1)", burn("3d"), burn("6h")),
			For:         "1h",
			Labels:      map[string]string{"severity": "ticket", "service": s.Service, "slo": s.Name},
			Annotations: ann(fmt.Sprintf("%s is spending budget faster than it accrues (3d)", s.Service), "08-sre-operations/runbooks/slo-burn.md"),
		},
		{
			Alert:       "SLOBudgetExhausted",
			Expr:        fmt.Sprintf("slo:error_budget_remaining%s <= 0", s.selector()),
			For:         "5m",
			Labels:      map[string]string{"severity": "ticket", "service": s.Service, "slo": s.Name},
			Annotations: ann(fmt.Sprintf("%s has no error budget left: release gate is closed", s.Service), "08-sre-operations/error-budget-policy.md"),
		},
	}
	return []group{rec, alerts}
}

// RenderRules renders Prometheus rule-file YAML for any number of SLOs.
func RenderRules(specs []*Spec) ([]byte, error) {
	var groups []group
	for _, s := range specs {
		groups = append(groups, s.Groups()...)
	}
	out, err := yaml.Marshal(map[string]any{"groups": groups})
	if err != nil {
		return nil, err
	}
	return append([]byte("# GENERATED by `budgetgate rules` from slos/*.yaml - do not edit.\n"), out...), nil
}
